const reEscape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const ERROR_PATTERNS = Object.entries(ERRORS_EN).map(([ja, en]) => [new RegExp(`^${ja.split('{}').map(reEscape).join('(.+?)')}$`), en]);

// 断りの文を画面の言語にする。辞書に無い文は、英語の画面では「うまくいきませんでした」にする（日本語を混ぜない）
export function translateError(message, lang) {
  if (lang !== 'en') return message;
  for (const [re, en] of ERROR_PATTERNS) {
    const m = String(message).match(re);
    if (m) { let i = 1; return en.replace(/\{\}/g, () => m[i++]); }
  }
  return ERRORS_EN['うまくいきませんでした'];
}

// ---- 少ない数をまとめた値（src/coarsen.mjs の「5未満」「8以上」「出さない」）と日本時間の日付を、言語に合わせる ----
const EN_DAYS = { 日: 'Sun', 月: 'Mon', 火: 'Tue', 水: 'Wed', 木: 'Thu', 金: 'Fri', 土: 'Sat' };

export function localizeValue(v, lang) {
  if (lang !== 'en' || typeof v !== 'string') return v;
  if (v === '出さない') return 'withheld';
  if (v === 'まだ') return 'not yet';
  let m = v.match(/^([\d.]+%?)未満$/);
  if (m) return `under ${m[1]}`;
  m = v.match(/^([\d.]+%?)以上$/);
  if (m) return `${m[1]} or more`;
  // 「2026-11-02（月）09:00」→「2026-11-02 (Mon) 09:00」
  m = v.match(/^(\d{4}-\d{2}-\d{2})（(.)）(.*)$/);
  if (m) return `${m[1]} (${EN_DAYS[m[2]] ?? m[2]})${m[3] ? ` ${m[3]}` : ''}`;
  return v;
}

