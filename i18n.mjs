export const LANGS = ['ja', 'en'];
export const DEFAULT_LANG = 'ja';
export const LANG_KEY = 'toi-voice-lang';

// 画面の言語: ?lang= → 前に選んだもの（localStorage）→ ブラウザの言語（ja で始まれば日本語、ほかは英語）
export function pickLang({ search = '', stored = null, navigatorLang = '' } = {}) {
  const q = new URLSearchParams(search).get('lang');
  if (LANGS.includes(q)) return q;
  if (LANGS.includes(stored)) return stored;
  if (!navigatorLang) return DEFAULT_LANG;
  return navigatorLang.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

